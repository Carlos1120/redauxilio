CREATE TABLE IF NOT EXISTS citizen_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  display_name VARCHAR(80) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  failed_login_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS citizen_publication (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000) PRIMARY KEY,
  author_id BIGINT NOT NULL REFERENCES citizen_account(id),
  category VARCHAR(20) NOT NULL,
  assistance_subtype VARCHAR(30),
  title VARCHAR(120) NOT NULL,
  description VARCHAR(1000) NOT NULL,
  location VARCHAR(160) NOT NULL,
  operational_status VARCHAR(40) NOT NULL,
  impact_type VARCHAR(40),
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  visible BOOLEAN NOT NULL DEFAULT TRUE,
  closed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS citizen_publication_author_time
  ON citizen_publication (author_id, created_at);

-- Los cambios son anexos inmutables desde la aplicación. Nunca se sobreescribe una versión.
CREATE TABLE IF NOT EXISTS citizen_publication_change (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication_id BIGINT NOT NULL REFERENCES citizen_publication(id),
  actor_id BIGINT NOT NULL REFERENCES citizen_account(id),
  action VARCHAR(16) NOT NULL,
  before_snapshot VARCHAR(4000) NOT NULL,
  after_snapshot VARCHAR(4000) NOT NULL,
  reason VARCHAR(500),
  changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS publication_change_publication
  ON citizen_publication_change (publication_id, id);
-- RA-05 conserva cada confirmación por versión; incrementar versión no borra historia.
ALTER TABLE citizen_publication ADD COLUMN IF NOT EXISTS confirmation_version BIGINT NOT NULL DEFAULT 1;
CREATE TABLE IF NOT EXISTS publication_confirmation (
  publication_id BIGINT NOT NULL REFERENCES citizen_publication(id),
  publication_version BIGINT NOT NULL,
  confirmer_id BIGINT NOT NULL REFERENCES citizen_account(id),
  confirmed_at TIMESTAMP WITH TIME ZONE NOT NULL,
  PRIMARY KEY (publication_id, publication_version, confirmer_id)
);
CREATE INDEX IF NOT EXISTS confirmation_account_time
  ON publication_confirmation (confirmer_id, confirmed_at);
CREATE TABLE IF NOT EXISTS publication_confirmation_invalidation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication_id BIGINT NOT NULL REFERENCES citizen_publication(id),
  actor_id BIGINT NOT NULL REFERENCES citizen_account(id),
  previous_version BIGINT NOT NULL,
  next_version BIGINT NOT NULL,
  reason VARCHAR(500) NOT NULL,
  invalidated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- RA-07: revisión separada de confianza, cierre y visibilidad.
ALTER TABLE citizen_publication ADD COLUMN IF NOT EXISTS review_status VARCHAR(20) NOT NULL DEFAULT 'SIN_REVISION';
CREATE TABLE IF NOT EXISTS publication_content_report (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication_id BIGINT NOT NULL REFERENCES citizen_publication(id),
  reporter_id BIGINT NOT NULL REFERENCES citizen_account(id),
  reason VARCHAR(500) NOT NULL,
  reported_at TIMESTAMP WITH TIME ZONE NOT NULL,
  -- 1 = activo; NULL = resuelto en una futura RA-08. NULL permite conservar varios históricos.
  active_slot SMALLINT DEFAULT 1 CHECK (active_slot IS NULL OR active_slot = 1),
  UNIQUE (publication_id, reporter_id, active_slot)
);
CREATE INDEX IF NOT EXISTS content_report_publication_active
  ON publication_content_report (publication_id, active_slot);
CREATE INDEX IF NOT EXISTS content_report_publication_history
  ON publication_content_report (publication_id, id);

-- RA-08: decisiones internas separadas del historial visible al autor.
CREATE TABLE IF NOT EXISTS publication_moderation_action (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication_id BIGINT NOT NULL REFERENCES citizen_publication(id),
  actor_id BIGINT NOT NULL REFERENCES citizen_account(id),
  action VARCHAR(16) NOT NULL,
  before_snapshot VARCHAR(4000) NOT NULL,
  after_snapshot VARCHAR(4000) NOT NULL,
  reason VARCHAR(500) NOT NULL,
  acted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS moderation_action_publication
  ON publication_moderation_action (publication_id, id);

-- RA-08: permiso interno persistente; el registro ciudadano nunca escribe estas tablas.
CREATE TABLE IF NOT EXISTS operator_permission (
  account_id BIGINT PRIMARY KEY REFERENCES citizen_account(id),
  role VARCHAR(20) NOT NULL CHECK (role = 'ROLE_OPERATOR'),
  granted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
-- Solicitud de aprovisionamiento única: reiniciar con la misma configuración no repite ni revierte decisiones.
CREATE TABLE IF NOT EXISTS operator_permission_audit (
  request_id VARCHAR(36) PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES citizen_account(id),
  actor VARCHAR(80) NOT NULL,
  action VARCHAR(8) NOT NULL CHECK (action IN ('GRANT', 'REVOKE')),
  before_granted BOOLEAN NOT NULL,
  after_granted BOOLEAN NOT NULL,
  reason VARCHAR(500) NOT NULL,
  changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
