CREATE TABLE IF NOT EXISTS citizen_account (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(254) NOT NULL UNIQUE,
  display_name VARCHAR(80) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  failed_login_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS citizen_publication (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000) PRIMARY KEY,
  author_id BIGINT NOT NULL REFERENCES citizen_account(id),
  category VARCHAR(20) NOT NULL,
  assistance_subtype VARCHAR(30),
  title VARCHAR(120) NOT NULL,
  description VARCHAR(1000) NOT NULL,
  location VARCHAR(160) NOT NULL,
  operational_status VARCHAR(40) NOT NULL,
  impact_type VARCHAR(40),
  latitude DOUBLE PRECISION NOT NULL,
  longitude DOUBLE PRECISION NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  visible BOOLEAN NOT NULL DEFAULT TRUE,
  closed BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS citizen_publication_author_time
  ON citizen_publication (author_id, created_at);
